export type Lang = "es" | "en";
const DICTS: Record<Lang, Record<TKey, string>> = { es, en };

type Params = Record<string, string | number>;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, params?: Params) => string;
  fmtTime: (ts: number) => string;
  fmtDateTime: (ts: number) => string;
  fmtDuration: (ms: number) => string;
  fmtPct: (n: number) => string;
}

const Ctx = createContext<I18n | null>(null);
const TZ = "America/Panama";

export function translate(lang: Lang, key: TKey, params?: Params) {
  let s = DICTS[lang][key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");
  useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === "es" || saved === "en") setLangState(saved);
    } catch {
      /* storage blocked: keep default */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);
  const value = useMemo<I18n>(() => {
    const locale = lang === "es" ? "es-PA" : "en-US";
    const time = new Intl.DateTimeFormat(locale, { timeZone: TZ, hour: "2-digit", minute: "2-digit" });
    const dt = new Intl.DateTimeFormat(locale, {
      timeZone: TZ,
      weekday: "short",
      day: "numeric",
      month: "short",
      hour: "2-digit",
      minute: "2-digit",
    });
    return {
      lang,
      setLang,
      t: (k, p) => translate(lang, k, p),
      fmtTime: (ts) => time.format(ts),
      fmtDateTime: (ts) => dt.format(ts),
      fmtDuration: (ms) => {
        const total = Math.floor(Math.abs(ms) / 60_000);
        const h = Math.floor(total / 60);
        const m = total % 60;
        return h ? `${h} ${DICTS[lang]["unit.h"]} ${m} ${DICTS[lang]["unit.min"]}` : `${m} ${DICTS[lang]["unit.min"]}`;
      },
      fmtPct: (n) => `${Math.round(n)} %`,
    };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
